import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { validateCourses } from "../assets/course-model.mjs";

export const configPath = fileURLToPath(new URL("../assets/course-config.json", import.meta.url));
export function configVersion(config) {
  return createHash("sha256").update(JSON.stringify(config)).digest("hex");
}
export function buildConfig() {
  const config = JSON.parse(readFileSync(configPath, "utf8"));
  validateCourses(config.courses, config);
  const version = configVersion(config);
  const output = `// Generated by npm run build:courses from course-config.json. Do not edit.\nwindow.JULIA_SITE_CONFIG = ${JSON.stringify({ ...config, dataVersion: version }, null, 2).replace(/</g, "\\u003c")};\n`;
  writeFileSync(new URL("../assets/course-config.js", import.meta.url), output);
  writeFileSync(new URL("../assets/course-version.json", import.meta.url), JSON.stringify({ version }) + "\n");
  return version;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildConfig();
